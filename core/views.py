    """
    Toggle whether MarketPulse should actively evaluate an
    AlertRule.

    Example:

        Enabled
            ↓
        rule can be evaluated

        Disabled
            ↓
        rule remains stored but is ignored
    """


    # ========================================================
    # 18.1 FIND CURRENT USER'S RULE
    # ========================================================

    alert_rule = (
        get_object_or_404(
            AlertRule,
            pk=rule_id,
            user=request.user,
        )
    )


    # ========================================================
    # 18.2 TOGGLE STATE
    # ========================================================

    alert_rule.is_enabled = (
        not
        alert_rule.is_enabled
    )


    # ========================================================
    # 18.3 SAVE STATE
    # ========================================================

    alert_rule.save(
        update_fields=[
            "is_enabled",
            "updated_at",
        ]
    )


    # ========================================================
    # 18.4 BUILD USER MESSAGE
    # ========================================================

    state = (

        "enabled"

        if alert_rule.is_enabled

        else "disabled"

    )


    messages.info(
        request,
        (
            f'{alert_rule.symbol} alert rule '
            f"was {state}."
        ),
    )


    # ========================================================
    # 18.5 RETURN TO DASHBOARD
    # ========================================================

    return redirect(
        "dashboard"
    )


