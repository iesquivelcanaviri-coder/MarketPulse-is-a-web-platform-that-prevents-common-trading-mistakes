# 11. HISTORICAL POSTGRESQL CHART DATA
# ============================================================

def _get_dashboard_chart_rows(  # Helper function: retrieves stored observations for the Dashboard.
    symbol,  # Parameter: ticker whose observations should be retrieved.
    limit=DASHBOARD_CHART_LIMIT,  # Default parameter concept: uses 60 unless another limit is supplied.
):
    """
    Retrieve stored historical OHLCV observations from the
    MarketData table.

    MarketData records are selected newest-first so the most
    recent observations can be limited efficiently.

    They are then reversed because charting libraries normally
    expect chronological ordering:

        oldest
            ↓
        newest
    """

    rows = list(  # Built-in list conversion: evaluates the QuerySet and stores model objects in a Python list.
        MarketData.objects  # ORM manager: begins a query against MarketData.
        .filter(  # QuerySet filter: restricts rows to one ticker.
            symbol=symbol  # Field lookup: SQL equivalent of WHERE symbol = selected ticker.
        )
        .order_by(  # ORM ordering: retrieves newest records first.
            "-date"  # Minus means descending date order.
        )[:limit]  # QuerySet slicing: SQL LIMIT equivalent.
    )

    rows.reverse()  # List method: changes newest→oldest into oldest→newest for chart display.

    return [  # List comprehension: converts Django model objects into plain dictionaries.
        {  # Dictionary: one browser-friendly market observation.
            "date":
                row.date.isoformat(),  # Method call: converts Python date into an ISO string such as 2026-10-07.
            "open_price":
                float(  # Type conversion: Decimal/database value becomes a JSON-friendly Python float.
                    row.open_price
                ),
            "high_price":
                float(
                    row.high_price
                ),
            "low_price":
                float(
                    row.low_price
                ),
            "close_price":
                float(
                    row.close_price
                ),
            "volume":
                row.volume,  # Attribute access: reads the volume field directly from the model instance.
        }
        for row  # List-comprehension loop variable.
        in rows  # Iterable: the historical model objects retrieved above.
    ]


