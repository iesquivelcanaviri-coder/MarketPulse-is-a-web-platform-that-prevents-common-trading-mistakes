# 13. EDIT GENERATED ALERT
# ============================================================

@login_required
@require_POST
def edit_alert(
    request,
    alert_id,
):
    """
    Update an Alert notification belonging to the authenticated
    user.

    IMPORTANT:

    This edits the generated notification itself.

    It does NOT alter an AlertRule monitoring condition.


    Security:

        user=request.user

    prevents a user from editing another user's alert simply by
    changing the numeric identifier in the URL.
    """


    # ========================================================
    # 13.1 FIND CURRENT USER'S ALERT
    # ========================================================

    alert = get_object_or_404(
        Alert,
        pk=alert_id,
        user=request.user,
    )


    # ========================================================
    # 13.2 BIND SUBMITTED VALUES
    # ========================================================

    form = AlertEditForm(
        request.POST,
        instance=alert,
    )


    # ========================================================
    # 13.3 SAVE VALID ALERT
    # ========================================================

    if form.is_valid():

        updated_alert = (
            form.save()
        )


        messages.success(
            request,
            (
                f'Alert "{updated_alert.title}" '
                f"was updated successfully."
            ),
        )


    # ========================================================
    # 13.4 INVALID ALERT FORM
    # ========================================================

    else:

        messages.error(
            request,
            (
                "The alert could not be updated. "
                "Please check the submitted values."
            ),
        )


    # ========================================================
    # 13.5 RETURN TO DASHBOARD
    # ========================================================

    return redirect(
        "dashboard"
    )


