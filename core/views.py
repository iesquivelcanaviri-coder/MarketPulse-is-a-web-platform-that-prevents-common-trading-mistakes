# 12. ALERT CHOICE HELPERS
# ============================================================

def _get_alert_type_choices():
    """
    Read Alert alert_type choices directly from Django's model
    field metadata.

    This avoids depending on a particular Python constant such
    as:

        Alert.ALERT_TYPES

    because the current model defines its configured choices
    through the field.
    """

    return (

        Alert._meta

        .get_field(
            "alert_type"
        )

        .choices

    )


# ============================================================

def _get_alert_severity_choices():
    """
    Read severity choices directly from the Alert model field.

    The Edit Alert interface can therefore remain aligned with
    the actual model configuration.
    """

    return (

        Alert._meta

        .get_field(
            "severity"
        )

        .choices

    )


