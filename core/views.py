# 9. SELECT DASHBOARD MARKET SYMBOL
# ============================================================

def _get_selected_dashboard_symbol(  # Helper function: leading underscore signals that this function is intended for internal use in this module.
    request,  # HttpRequest parameter containing URL query-string data.
):
    """
    Read the selected Dashboard benchmark from the URL.

    Examples:

        /dashboard/?symbol=SPY
        /dashboard/?symbol=QQQ

    This helper controls the traditional benchmark context used
    by the Django-rendered Dashboard.

    The interactive stock-search workspace can load arbitrary
    symbols independently through JavaScript and the Alpaca API.
    """

    symbol = (  # Variable assignment: stores the cleaned ticker symbol.
        request.GET  # Django QueryDict: contains values from the URL query string.
        .get(  # Dictionary-like method: returns one query-string value.
            "symbol",  # Query-string key to read.
            "SPY",  # Default value when symbol is missing.
        )
        .strip()  # String method: removes spaces from both ends.
        .upper()  # String method: converts the ticker to uppercase.
    )

    if (  # Conditional statement: validates the selected ticker.
        symbol
        not in  # Membership operator: checks whether the ticker is absent from the dictionary.
        DASHBOARD_BENCHMARKS
    ):
        symbol = (  # Assignment: invalid values fall back to SPY.
            "SPY"
        )

    return symbol  # Return statement: gives the validated ticker back to the calling function.


