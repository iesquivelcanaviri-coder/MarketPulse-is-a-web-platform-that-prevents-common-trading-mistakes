# 10. LATEST MARKET CONDITION
# ============================================================

def _get_latest_market_condition(
    symbol,
):
    """
    Retrieve the newest stored Market Condition analysis for the
    selected Dashboard benchmark.

    MarketRegime belongs to the internal analytics layer.

    The Dashboard surfaces only the most recent result so the
    user receives useful market context without exposing a
    separate Analysis application.
    """

    regime = (

        MarketRegime.objects

        .filter(
            symbol=symbol
        )

        .order_by(
            "-date",
            "-created_at",
        )

        .first()

    )


    if regime is None:

        return None


    # --------------------------------------------------------
    # REGIME DISPLAY NAME
    # --------------------------------------------------------

    try:

        display_name = (
            regime.get_regime_display()
        )


    except AttributeError:

        display_name = (
            regime.regime
        )


    return {

        "id":
            regime.pk,

        "symbol":
            regime.symbol,

        "date":
            regime.date,

        "regime":
            regime.regime,

        "display":
            display_name,

        "confidence":
            (
                float(
                    regime.confidence
                )

                if regime.confidence is not None

                else None
            ),

        "volatility":
            (
                float(
                    regime.volatility
                )

                if regime.volatility is not None

                else None
            ),

        "trend_strength":
            (
                float(
                    regime.trend_strength
                )

                if regime.trend_strength is not None

                else None
            ),

    }


