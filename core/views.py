# 16. CREATE ALERT RULE
# ============================================================

@login_required
@require_POST
def create_alert_rule(
    request,
):
    """
    Create a configurable market-monitoring rule.

    Framework mapping:

    Dashboard
        ↓
    Add Alert
        ↓
    POST
        ↓
    AlertRuleForm
        ↓
    AlertRule
        ↓
    PostgreSQL


    Example:

        Symbol:
            AAPL

        Metric:
            Price

        Operator:
            Greater Than

        Threshold:
            260

        Result:

            MarketPulse can later monitor whether:

                AAPL price > 260
    """


    # ========================================================
    # 16.1 BIND CREATE FORM
    # ========================================================

    form = (
        AlertRuleForm(
            request.POST
        )
    )


    # ========================================================
    # 16.2 VALID RULE
    # ========================================================

    if form.is_valid():

        alert_rule = (
            form.save(
                commit=False
            )
        )


        # ----------------------------------------------------
        # SECURITY:
        #
        # User ownership is assigned server-side.
        #
        # It is intentionally NOT trusted from form input.
        # ----------------------------------------------------

        alert_rule.user = (
            request.user
        )


        alert_rule.save()


        messages.success(
            request,
            (
                f'Alert rule for "{alert_rule.symbol}" '
                f"was created successfully."
            ),
        )


    # ========================================================
    # 16.3 INVALID RULE
    # ========================================================

    else:

        messages.error(
            request,
            (
                "The alert rule could not be created. "
                "Please check the submitted values."
            ),
        )


    # ========================================================
    # 16.4 RETURN TO DASHBOARD
    # ========================================================

    return redirect(
        "dashboard"
    )


