@login_required  # Authentication decorator: login required.
@require_POST  # HTTP-method decorator: GET requests cannot perform this modifying action.
def edit_alert(  # View function: updates one generated Alert.
    request,  # Current HTTP request.
    alert_id,  # URL parameter: database primary key supplied by the route.
):
    """
    Update an Alert notification belonging to the authenticated
    user.

    This edits the generated notification itself.

    It does NOT alter an AlertRule monitoring condition.

    Security:

        user=request.user

    prevents a user from editing another user's alert simply by
    changing the numeric identifier in the URL.
    """

    alert = get_object_or_404(  # Secure object lookup: missing or unauthorised object returns HTTP 404.
        Alert,  # Model class being queried.
        pk=alert_id,  # Primary-key lookup from the URL.
        user=request.user,  # Authorization condition: Alert must belong to current user.
    )

    form = AlertEditForm(  # Form-class instantiation: binds submitted POST data to existing Alert.
        request.POST,  # QueryDict containing submitted form fields.
        instance=alert,  # ModelForm concept: update this existing database object instead of creating a new one.
    )

    if form.is_valid():  # Conditional statement: continue only if Django form validation succeeds.
        updated_alert = (  # Assignment: stores saved Alert object.
            form.save()  # ModelForm CRUD operation: writes validated changes to database.
        )

        messages.success(  # Django messages framework: creates one-time success notification.
            request,  # Current request/session.
            (
                f'Alert "{updated_alert.title}" '  # f-string concept: embeds a Python value inside a string.
                f"was updated successfully."
            ),
        )
    else:  # Branch statement: runs when validation fails.
        messages.error(  # One-time error notification.
            request,
            (
                "The alert could not be updated. "
                "Please check the submitted values."
            ),
        )

    return redirect(  # Post/Redirect/Get workflow: send browser back to Dashboard after modification.
        "dashboard"  # Named Django URL route.
    )


