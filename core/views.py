def home(
    request,
):
    """
    Render the MarketPulse landing page.

    The Home page combines:

    - MarketPulse purpose
    - Current technology stack
    - Core application features
    - Community activity
    - Inbox preview
    - Complete feature guide
    - Educational notice


    Public visitors can see:

    - platform information
    - feature descriptions
    - recent Community activity


    Authenticated users can additionally see:

    - recent private messages
    - unread private message count


    Actual post creation and private-message management remain
    inside community/views.py.
    """


    # ========================================================
    # 6.1 RECENT COMMUNITY POSTS
    # ========================================================

    # Load only a small number of Community posts because the
    # Home page should provide a preview rather than reproduce
    # the complete Community Feed.
    #
    # select_related("author") retrieves the related user
    # record in the same query and avoids unnecessary database
    # queries while rendering the template.

    recent_posts = (

        CommunityPost.objects

        .select_related(
            "author"
        )

        .order_by(
            "-created_at"
        )[:4]

    )


    # ========================================================
    # 6.2 DEFAULT INBOX VALUES
    # ========================================================

    # Anonymous visitors do not have access to a private Inbox.
    #
    # An empty QuerySet allows the Home template to safely loop
    # through recent_messages regardless of authentication.

    recent_messages = (
        PrivateMessage.objects.none()
    )


    unread_messages = 0


    # ========================================================
    # 6.3 AUTHENTICATED USER INBOX
    # ========================================================

    if request.user.is_authenticated:


        # ----------------------------------------------------
        # RECENT RECEIVED MESSAGES
        # ----------------------------------------------------

        # Only messages belonging to the currently authenticated
        # recipient are returned.
        #
        # This is essential because one user must never be able
        # to view another user's private Inbox.

        recent_messages = (

            PrivateMessage.objects

            .filter(
                recipient=request.user
            )

            .select_related(
                "sender"
            )

            .order_by(
                "-created_at"
            )[:4]

        )


        # ----------------------------------------------------
        # UNREAD MESSAGE COUNT
        # ----------------------------------------------------

        unread_messages = (

            PrivateMessage.objects

            .filter(
                recipient=request.user,
                is_read=False,
            )

            .count()

        )


    # ========================================================
    # 6.4 HOME PAGE CONTEXT
    # ========================================================

    context = {


        # ----------------------------------------------------
        # CURRENT MARKETPULSE TECHNOLOGY
        # ----------------------------------------------------

        "home_technology_stack":
            HOME_TECHNOLOGY_STACK,


        # ----------------------------------------------------
        # CORE APPLICATION FEATURES
        # ----------------------------------------------------

        "home_core_features":
            HOME_CORE_FEATURES,


        # ----------------------------------------------------
        # ABOUT MARKETPULSE
        # ----------------------------------------------------

        "home_about_description":
            HOME_ABOUT_DESCRIPTION,

        "home_purpose_summary":
            HOME_PURPOSE_SUMMARY,


        # ----------------------------------------------------
        # COMPLETE FEATURE GUIDE
        # ----------------------------------------------------

        "home_feature_guide":
            HOME_FEATURE_GUIDE,


        # ----------------------------------------------------
        # EDUCATIONAL NOTICE
        # ----------------------------------------------------

        "home_educational_notice":
            HOME_EDUCATIONAL_NOTICE,


        # ----------------------------------------------------
        # COMMUNITY
        # ----------------------------------------------------

        "recent_posts":
            recent_posts,


        # ----------------------------------------------------
        # PRIVATE MESSAGING
        # ----------------------------------------------------

        "recent_messages":
            recent_messages,

        "unread_messages":
            unread_messages,


        # Alternative descriptive name is also provided so
        # templates or future components can use either name.

        "unread_message_count":
            unread_messages,

    }


    # ========================================================
    # 6.5 RENDER HOME PAGE
    # ========================================================

    return render(
        request,
        "home.html",
        context,
    )


