# 19. ENABLE / DISABLE ALERT RULE
# ============================================================

@login_required
@require_POST
def toggle_alert_rule(
    request,
    rule_id,
):
    """
    Toggle whether MarketPulse should actively evaluate an
    AlertRule.
    """

    alert_rule = (
        get_object_or_404(
            AlertRule,
            pk=rule_id,
            user=request.user,
        )
    )


    alert_rule.is_enabled = (
        not
        alert_rule.is_enabled
    )


    alert_rule.save(
        update_fields=[
            "is_enabled",
            "updated_at",
        ]
    )


    state = (

        "enabled"

        if alert_rule.is_enabled

        else "disabled"

    )


    messages.info(
        request,
        (
            f'{alert_rule.symbol} alert rule '
            f"was {state}."
        ),
    )


    return redirect(
        "dashboard"
    )


