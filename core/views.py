# 8. HOME PAGE VIEW
# ============================================================

def home(  # Function definition concept: creates a reusable block of code called home.
    request,  # Function parameter: Django passes the current HttpRequest object into the view.
):
    """
    Render the MarketPulse landing page.

    The Home page combines:

    - MarketPulse purpose
    - Current technology stack
    - Core application features
    - Community activity
    - Inbox preview
    - Complete feature guide
    - Educational notice

    Public visitors can see:

    - platform information
    - feature descriptions
    - recent Community activity

    Authenticated users can additionally see:

    - recent private messages
    - unread private message count

    Actual post creation and private-message management remain
    inside community/views.py.
    """

    # ========================================================
    # 8.1 RECENT COMMUNITY POSTS
    # ========================================================

    recent_posts = (  # Variable assignment: stores the QuerySet returned by the ORM.
        CommunityPost.objects  # Django ORM manager: begins a database query against CommunityPost.
        .select_related(  # ORM optimisation: retrieves the related author in the same SQL query.
            "author"  # Relationship name: CommunityPost.author.
        )
        .order_by(  # QuerySet method: sorts the database results.
            "-created_at"  # Minus prefix means newest records appear first.
        )[:4]  # QuerySet slicing: returns only the first four records.
    )

    # ========================================================
    # 8.2 DEFAULT PRIVATE-INBOX VALUES
    # ========================================================

    recent_messages = (  # Variable assignment: creates a safe default for anonymous visitors.
        PrivateMessage.objects.none()  # ORM method: creates an empty QuerySet without retrieving messages.
    )
    unread_messages = 0  # Integer assignment: anonymous users begin with zero unread private messages.

    # ========================================================
    # 8.3 AUTHENTICATED USER INBOX
    # ========================================================

    if request.user.is_authenticated:  # Conditional statement: this block runs only when the request belongs to a logged-in user.
        recent_messages = (  # Variable reassignment: replace the empty QuerySet with the user's messages.
            PrivateMessage.objects  # ORM manager: starts a query against PrivateMessage.
            .filter(  # QuerySet filtering: restricts which database rows are returned.
                recipient=request.user  # Security condition: only messages addressed to the logged-in user are selected.
            )
            .select_related(  # ORM optimisation: retrieves sender information in the same query.
                "sender"  # Foreign-key relationship being loaded.
            )
            .order_by(  # ORM ordering: controls the order returned from PostgreSQL.
                "-created_at"  # Newest messages appear first.
            )[:4]  # QuerySet slice: Home page displays only the newest four messages.
        )

        unread_messages = (  # Assignment: stores the number of unread messages.
            PrivateMessage.objects  # ORM manager: starts another PrivateMessage query.
            .filter(  # ORM filter: applies multiple database conditions.
                recipient=request.user,  # Security condition: message must belong to current user.
                is_read=False,  # Boolean condition: only unread messages are included.
            )
            .count()  # ORM aggregation method: asks the database to count matching records.
        )

    # ========================================================
    # 8.4 HOME TEMPLATE CONTEXT
    # ========================================================

    context = {  # Dictionary concept: creates the named data passed from the Django view to home.html.
        "home_technology_stack":  # Template context key.
            HOME_TECHNOLOGY_STACK,  # Context value: technology-stack list.
        "home_core_features":
            HOME_CORE_FEATURES,
        "home_about_description":
            HOME_ABOUT_DESCRIPTION,
        "home_purpose_summary":
            HOME_PURPOSE_SUMMARY,
        "home_feature_guide":
            HOME_FEATURE_GUIDE,
        "home_educational_notice":
            HOME_EDUCATIONAL_NOTICE,
        "recent_posts":
            recent_posts,
        "recent_messages":
            recent_messages,
        "unread_messages":
            unread_messages,
        "unread_message_count":
            unread_messages,  # Same value is provided under a second descriptive context name.
    }

    # ========================================================
    # 8.5 RENDER HOME TEMPLATE
    # ========================================================

    return render(  # Return statement: ends the function and gives Django an HttpResponse.
        request,  # Current browser request.
        "home.html",  # Template file Django should render.
        context,  # Dictionary of data available inside the template.
    )


