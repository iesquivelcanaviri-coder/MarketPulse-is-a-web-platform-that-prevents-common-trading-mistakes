# 12. LATEST MARKET CONDITION
# ============================================================

def _get_latest_market_condition(  # Helper function: retrieves the latest analytical regime result for a ticker.
    symbol,  # Parameter: ticker being analysed.
):
    """
    Retrieve the newest stored Market Condition analysis for the
    selected Dashboard benchmark.

    MarketRegime belongs to the internal analytics layer.

    The Dashboard surfaces only the most recent result so the
    user receives useful market context without exposing a
    separate Analysis application.
    """

    regime = (  # Variable assignment: will hold a MarketRegime object or None.
        MarketRegime.objects  # ORM manager: begins query against the analytics model.
        .filter(  # QuerySet filter: keeps rows matching the selected ticker.
            symbol=symbol  # Field equality lookup.
        )
        .order_by(  # QuerySet ordering: newest analytical result should appear first.
            "-date",  # Primary descending sort by market date.
            "-created_at",  # Secondary descending sort by database creation time.
        )
        .first()  # QuerySet method: returns the first result or None.
    )

    if regime is None:  # Identity comparison: checks specifically for the Python None object.
        return None  # Early return: no Market Condition exists for this ticker.

    try:  # Exception-handling concept: attempt code that may not exist on every model implementation.
        display_name = (  # Assignment: human-readable regime label.
            regime.get_regime_display()  # Django model method automatically generated for fields using choices.
        )
    except AttributeError:  # Exception handler: runs if get_regime_display does not exist.
        display_name = (  # Fallback assignment.
            regime.regime  # Raw stored regime value.
        )

    return {  # Dictionary: converts the model result into simple Dashboard context data.
        "id":
            regime.pk,  # Primary-key attribute.
        "symbol":
            regime.symbol,  # Model field.
        "date":
            regime.date,  # Model date field.
        "regime":
            regime.regime,  # Raw classification value.
        "display":
            display_name,  # Human-readable classification value.
        "confidence":
            (  # Conditional expression: returns a float only when a value exists.
                float(
                    regime.confidence
                )
                if regime.confidence is not None
                else None
            ),
        "volatility":
            (
                float(
                    regime.volatility
                )
                if regime.volatility is not None
                else None
            ),
        "trend_strength":
            (
                float(
                    regime.trend_strength
                )
                if regime.trend_strength is not None
                else None
            ),
    }


