# 7. SELECT DASHBOARD MARKET SYMBOL
# ============================================================

def _get_selected_dashboard_symbol(
    request,
):
    """
    Read the selected Dashboard benchmark from the URL.

    Examples:

        /dashboard/?symbol=SPY

        /dashboard/?symbol=QQQ


    This helper controls the traditional benchmark context used
    by the Django-rendered Dashboard.

    The interactive stock-search workspace can load arbitrary
    symbols independently through JavaScript and the Alpaca API.
    """

    symbol = (
        request.GET
        .get(
            "symbol",
            "SPY",
        )
        .strip()
        .upper()
    )


    if (
        symbol
        not in
        DASHBOARD_BENCHMARKS
    ):

        symbol = (
            "SPY"
        )


    return symbol


# ============================================================
# 8. AVAILABLE HISTORICAL CHART SYMBOLS
# ============================================================

def _get_available_chart_symbols():
    """
    Return benchmark symbols that already have historical
    MarketData observations stored in PostgreSQL.

    This information remains useful for:

    - fallback historical charts
    - data-health information
    - strategy testing
    - Market Condition analysis

    Live Alpaca graph availability is handled separately by the
    API layer.
    """

    stored_symbols = set(

        MarketData.objects

        .filter(
            symbol__in=list(
                DASHBOARD_BENCHMARKS.keys()
            )
        )

        .values_list(
            "symbol",
            flat=True,
        )

        .distinct()

    )


    return [

        symbol

        for symbol
        in DASHBOARD_BENCHMARKS

        if symbol in stored_symbols

    ]


# ============================================================
# 9. HISTORICAL POSTGRESQL CHART DATA
# ============================================================

def _get_dashboard_chart_rows(
    symbol,
    limit=DASHBOARD_CHART_LIMIT,
):
    """
    Retrieve stored historical OHLCV observations from the
    MarketData table.

    MarketData records are selected newest-first so the most
    recent observations can be limited efficiently.

    They are then reversed because charting libraries normally
    expect chronological ordering:

        oldest
            ↓
        newest
    """

    rows = list(

        MarketData.objects

        .filter(
            symbol=symbol
        )

        .order_by(
            "-date"
        )[:limit]

    )


    rows.reverse()


    # --------------------------------------------------------
    # Convert Decimal and Date objects into browser-friendly
    # Python values.
    # --------------------------------------------------------

    return [

        {

            "date":
                row.date.isoformat(),

            "open_price":
                float(
                    row.open_price
                ),

            "high_price":
                float(
                    row.high_price
                ),

            "low_price":
                float(
                    row.low_price
                ),

            "close_price":
                float(
                    row.close_price
                ),

            "volume":
                row.volume,

        }

        for row
        in rows

    ]


