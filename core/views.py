# 10. MARKET DATA HEALTH
# ============================================================

def _get_market_data_health():
    """
    Summarise the historical MarketData currently stored in
    PostgreSQL.

    This provides the Dashboard with information about:

    - total observations
    - number of stored symbols
    - earliest historical observation
    - latest historical observation
    - approximate data staleness
    """

    # --------------------------------------------------------
    # TOTAL OHLCV ROWS
    # --------------------------------------------------------

    total_rows = (
        MarketData.objects
        .count()
    )


    # --------------------------------------------------------
    # DISTINCT SYMBOL COUNT
    # --------------------------------------------------------

    stored_symbol_count = (

        MarketData.objects

        .values(
            "symbol"
        )

        .distinct()

        .count()

    )


    # --------------------------------------------------------
    # LATEST STORED OBSERVATION
    # --------------------------------------------------------

    latest_date = (

        MarketData.objects

        .order_by(
            "-date"
        )

        .values_list(
            "date",
            flat=True,
        )

        .first()

    )


    # --------------------------------------------------------
    # EARLIEST STORED OBSERVATION
    # --------------------------------------------------------

    earliest_date = (

        MarketData.objects

        .order_by(
            "date"
        )

        .values_list(
            "date",
            flat=True,
        )

        .first()

    )


    # --------------------------------------------------------
    # STALENESS
    # --------------------------------------------------------

    days_since_latest = None


    if latest_date:

        days_since_latest = (

            timezone.localdate()
            -
            latest_date

        ).days


    return {

        "total_rows":
            total_rows,

        "stored_symbols":
            stored_symbol_count,

        "earliest_date":
            earliest_date,

        "latest_date":
            latest_date,

        "days_since_latest":
            days_since_latest,

    }


