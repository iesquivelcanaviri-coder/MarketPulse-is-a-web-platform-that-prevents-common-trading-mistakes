# 10. AVAILABLE HISTORICAL CHART SYMBOLS
# ============================================================

def _get_available_chart_symbols():  # Helper function: no arguments are required.
    """
    Return benchmark symbols that already have historical
    MarketData observations stored in PostgreSQL.

    This remains useful for:

    - fallback historical charts
    - data-health information
    - strategy testing
    - Market Condition analysis

    Live Alpaca graph availability is handled separately by the
    API layer.
    """

    stored_symbols = set(  # Built-in set concept: stores unique ticker symbols for fast membership checking.
        MarketData.objects  # ORM manager: begins a MarketData query.
        .filter(  # QuerySet filtering: restricts records to supported Dashboard benchmarks.
            symbol__in=list(  # Django __in lookup: SQL equivalent of WHERE symbol IN (...).
                DASHBOARD_BENCHMARKS.keys()  # Dictionary method: returns the benchmark ticker keys.
            )
        )
        .values_list(  # ORM projection: asks PostgreSQL for only one column rather than complete model objects.
            "symbol",  # Database/model field being selected.
            flat=True,  # flat=True returns a simple sequence instead of one-item tuples.
        )
        .distinct()  # SQL DISTINCT concept: removes duplicate ticker values.
    )

    return [  # List comprehension concept: creates a new list from an iterable with a condition.
        symbol  # Value to place into the returned list.
        for symbol  # Loop portion of the comprehension.
        in DASHBOARD_BENCHMARKS  # Iterates through configured benchmark dictionary keys.
        if symbol in stored_symbols  # Filter condition: keeps only symbols that exist in PostgreSQL.
    ]


