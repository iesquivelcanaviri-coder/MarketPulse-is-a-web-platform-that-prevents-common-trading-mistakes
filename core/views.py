@login_required
def dashboard(
    request,
):
    """
    Render the authenticated MarketPulse Dashboard.

    Framework mapping:

    Browser
        ↓
    dashboard()
        ↓
    Django ORM
        ↓
    PostgreSQL
        ↓
    dashboard.html
        ↓
    JavaScript
        ↓
    MarketPulse REST API
        ↓
    Alpaca


    The page combines:

    - user strategies
    - backtests
    - historical PostgreSQL data
    - Market Condition analysis
    - generated Alerts
    - configurable AlertRules
    - Alpaca live market information
    """


    # ========================================================
    # 12.1 USER STRATEGIES
    # ========================================================

    strategies = (

        Strategy.objects

        .filter(
            user=request.user
        )

        .order_by(
            "-created_at"
        )

    )


    active_strategies = (

        strategies

        .filter(
            is_active=True
        )

    )


    # ========================================================
    # 12.2 USER BACKTESTS
    # ========================================================

    backtests = (

        Backtest.objects

        .filter(
            strategy__user=request.user
        )

        .select_related(
            "strategy"
        )

        .order_by(
            "-created_at"
        )

    )


    latest_backtest = (
        backtests.first()
    )


    # ========================================================
    # 12.3 AVERAGE WIN RATE
    # ========================================================

    average_win_rate = (

        backtests

        .aggregate(
            value=Avg(
                "win_rate"
            )
        )

        .get(
            "value"
        )

        or
        0

    )


    # Backtest.win_rate is stored as a decimal ratio.
    #
    # Example:
    #
    #     0.58
    #
    # becomes:
    #
    #     58%

    average_win_rate_pct = (

        float(
            average_win_rate
        )

        *
        100

    )


    # ========================================================
    # 12.4 GENERATED USER ALERTS
    # ========================================================

    # Alert represents an event or notification already created
    # by MarketPulse.
    #
    # These are intentionally separate from AlertRule.

    alerts = (

        Alert.objects

        .filter(
            user=request.user
        )

        .order_by(
            "-is_active",
            "-created_at",
        )

    )


    # --------------------------------------------------------
    # ACTIVE GENERATED ALERTS
    # --------------------------------------------------------

    active_alerts = (

        alerts

        .filter(
            is_active=True
        )

    )


    # --------------------------------------------------------
    # UNREAD GENERATED ALERTS
    # --------------------------------------------------------

    unread_alerts = (

        alerts

        .filter(
            is_read=False
        )

    )


    # ========================================================
    # 12.5 CONFIGURABLE ALERT RULES
    # ========================================================

    # AlertRule represents what the user wants MarketPulse to
    # monitor.
    #
    # Example:
    #
    #     AAPL
    #     Price
    #     >
    #     260
    #
    # The rules will appear underneath the professional chart
    # and can be created, edited, enabled/disabled or deleted.

    alert_rules = (

        AlertRule.objects

        .filter(
            user=request.user
        )

        .order_by(
            "-is_enabled",
            "symbol",
            "metric",
            "-created_at",
        )

    )


    # --------------------------------------------------------
    # ENABLED RULES
    # --------------------------------------------------------

    enabled_alert_rules = (

        alert_rules

        .filter(
            is_enabled=True
        )

    )


    # --------------------------------------------------------
    # BLANK CREATE RULE FORM
    # --------------------------------------------------------

    alert_rule_form = (
        AlertRuleForm()
    )


    # ========================================================
    # 12.6 GENERATED ALERT FORM OPTIONS
    # ========================================================

    # Read directly from model metadata rather than depending
    # on hard-coded constants.

    alert_type_choices = (
        _get_alert_type_choices()
    )


    alert_severity_choices = (
        _get_alert_severity_choices()
    )


    # ========================================================
    # 12.7 SELECT DEFAULT MARKET BENCHMARK
    # ========================================================

    selected_symbol = (

        _get_selected_dashboard_symbol(
            request
        )

    )


    # ========================================================
    # 12.8 STORED POSTGRESQL HISTORICAL GRAPH DATA
    # ========================================================

    # This remains available for:
    #
    # - fallback rendering
    # - data-health information
    # - analytics
    #
    # The new interactive trading chart will primarily request
    # current historical data from Alpaca through the API.

    chart_rows = (

        _get_dashboard_chart_rows(
            selected_symbol
        )

    )


    available_chart_symbols = (
        _get_available_chart_symbols()
    )


    # ========================================================
    # 12.9 MARKET CONDITION
    # ========================================================

    market_condition = (

        _get_latest_market_condition(
            selected_symbol
        )

    )


    # ========================================================
    # 12.10 DATA HEALTH
    # ========================================================

    data_health = (
        _get_market_data_health()
    )


    # ========================================================
    # 12.11 DASHBOARD CONTEXT
    # ========================================================

    context = {


        # ----------------------------------------------------
        # USER / STRATEGY STATISTICS
        # ----------------------------------------------------

        "active_strategy_count":
            active_strategies.count(),

        "strategy_count":
            strategies.count(),

        "backtest_count":
            backtests.count(),

        "avg_win_rate":
            average_win_rate_pct,

        "market_data_count":
            data_health[
                "total_rows"
            ],


        # ----------------------------------------------------
        # STRATEGIES / BACKTESTS
        # ----------------------------------------------------

        "strategies":
            strategies,

        "latest_backtest":
            latest_backtest,

        "recent_backtests":
            backtests[:5],


        # ----------------------------------------------------
        # GENERATED ALERT MANAGEMENT
        # ----------------------------------------------------

        "alerts":
            alerts,

        "active_alerts":
            active_alerts,

        "active_alert_count":
            active_alerts.count(),

        "unread_alert_count":
            unread_alerts.count(),

        "alert_type_choices":
            alert_type_choices,

        "alert_severity_choices":
            alert_severity_choices,


        # ----------------------------------------------------
        # CONFIGURABLE ALERT RULES
        # ----------------------------------------------------

        "alert_rules":
            alert_rules,

        "alert_rule_count":
            alert_rules.count(),

        "enabled_alert_rules":
            enabled_alert_rules,

        "enabled_alert_rule_count":
            enabled_alert_rules.count(),

        "alert_rule_form":
            alert_rule_form,


        # ----------------------------------------------------
        # MARKET OVERVIEW
        # ----------------------------------------------------

        "dashboard_benchmarks":
            DASHBOARD_BENCHMARKS,

        "selected_symbol":
            selected_symbol,

        "available_chart_symbols":
            available_chart_symbols,

        "market_chart_rows":
            chart_rows,

        "market_chart_has_data":
            bool(
                chart_rows
            ),

        "market_condition":
            market_condition,


        # ----------------------------------------------------
        # DATA HEALTH
        # ----------------------------------------------------

        "data_health":
            data_health,


        # ----------------------------------------------------
        # AUTOMATIC ALPACA REFRESH
        # ----------------------------------------------------

        "dashboard_refresh_seconds":
            DASHBOARD_REFRESH_SECONDS,

    }


    # ========================================================
    # 12.12 RENDER DASHBOARD
    # ========================================================

    return render(
        request,
        "dashboard.html",
        context,
    )


