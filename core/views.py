# 15. TOGGLE GENERATED ALERT RESOLUTION
# ============================================================

@login_required
@require_POST
def toggle_alert_resolution(
    request,
    alert_id,
):
    """
    Resolve an active generated Alert or reopen a previously
    resolved Alert.

    Alert records are preserved instead of deleted because they
    provide historical evidence of conditions detected by
    MarketPulse.
    """


    # ========================================================
    # 15.1 FIND USER ALERT
    # ========================================================

    alert = get_object_or_404(
        Alert,
        pk=alert_id,
        user=request.user,
    )


    # ========================================================
    # 15.2 ACTIVE → RESOLVED
    # ========================================================

    if alert.is_active:

        alert.resolve()


        messages.success(
            request,
            f'Alert "{alert.title}" was resolved.',
        )


    # ========================================================
    # 15.3 RESOLVED → ACTIVE
    # ========================================================

    else:

        alert.reopen()


        messages.info(
            request,
            f'Alert "{alert.title}" was reopened.',
        )


    # ========================================================
    # 15.4 RETURN TO DASHBOARD
    # ========================================================

    return redirect(
        "dashboard"
    )


