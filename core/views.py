@login_required  # Decorator: unauthenticated users are redirected to LOGIN_URL before this function can run.
def dashboard(  # Function definition: authenticated Dashboard controller.
    request,  # HttpRequest object supplied by Django.
):
    """
    Render the authenticated MarketPulse Dashboard.

    Framework mapping:

    Browser
        ↓
    dashboard()
        ↓
    Django ORM
        ↓
    PostgreSQL
        ↓
    dashboard.html
        ↓
    JavaScript
        ↓
    MarketPulse REST API
        ↓
    Alpaca

    The page combines:

    - user strategies
    - backtests
    - historical PostgreSQL data
    - Market Condition analysis
    - generated Alerts
    - configurable AlertRules
    - Alpaca live market information
    """

    # ========================================================
    # 15.1 USER STRATEGIES
    # ========================================================

    strategies = (  # Assignment: QuerySet containing strategies belonging to the current authenticated user.
        Strategy.objects  # ORM manager for Strategy.
        .filter(  # Security/user filtering.
            user=request.user  # Foreign-key equality: only this user's strategies.
        )
        .order_by(  # Sort strategy records.
            "-created_at"  # Newest first.
        )
    )

    active_strategies = (  # QuerySet refinement: starts from the strategies QuerySet above.
        strategies
        .filter(  # Additional SQL condition.
            is_active=True  # Boolean filter: only active strategies.
        )
    )

    # ========================================================
    # 15.2 USER BACKTESTS
    # ========================================================

    backtests = (  # Assignment: retrieves backtests connected to the current user's strategies.
        Backtest.objects  # ORM manager.
        .filter(  # Relationship traversal using Django's double-underscore syntax.
            strategy__user=request.user  # Follow Backtest.strategy → Strategy.user.
        )
        .select_related(  # ORM optimisation: retrieve associated Strategy in same SQL query.
            "strategy"
        )
        .order_by(  # Sort result set.
            "-created_at"  # Newest backtests first.
        )
    )

    latest_backtest = (  # Assignment: newest Backtest object or None.
        backtests.first()  # QuerySet method: retrieves first item.
    )

    # ========================================================
    # 15.3 AVERAGE WIN RATE
    # ========================================================

    average_win_rate = (  # Assignment: stores aggregated average or zero.
        backtests
        .aggregate(  # ORM aggregate concept: calculates one summary value across many rows.
            value=Avg(  # Avg database function.
                "win_rate"  # Model field being averaged.
            )
        )
        .get(  # Dictionary method: reads result generated under alias "value".
            "value"
        )
        or  # Boolean operator: use zero when database result is None/falsy.
        0
    )

    average_win_rate_pct = (  # Assignment: converts stored decimal proportion into percentage.
        float(  # Type conversion: database numeric value becomes Python float.
            average_win_rate
        )
        *
        100  # Arithmetic multiplication: for example 0.55 becomes 55.
    )

    # ========================================================
    # 15.4 GENERATED USER ALERTS
    # ========================================================

    alerts = (  # Assignment: QuerySet of Alerts owned by current user.
        Alert.objects  # ORM manager.
        .filter(  # Security filtering.
            user=request.user  # Only current user's alerts.
        )
        .order_by(  # Multi-field sorting.
            "-is_active",  # Active alerts first.
            "-created_at",  # Then newest alerts first.
        )
    )

    active_alerts = (  # QuerySet derived from alerts.
        alerts
        .filter(  # Additional filtering.
            is_active=True  # Only unresolved/active alerts.
        )
    )

    unread_alerts = (  # QuerySet derived from alerts.
        alerts
        .filter(  # Additional filtering.
            is_read=False  # Only alerts not yet acknowledged.
        )
    )

    # ========================================================
    # 15.5 CONFIGURABLE ALERT RULES
    # ========================================================

    alert_rules = (  # Assignment: all monitoring rules belonging to current user.
        AlertRule.objects  # ORM manager.
        .filter(  # Security filtering.
            user=request.user  # Only current user's rules.
        )
        .order_by(  # Multi-column ordering.
            "-is_enabled",  # Enabled rules first.
            "symbol",  # Then alphabetically by ticker.
            "metric",  # Then by monitored metric.
            "-created_at",  # Newest rules first within otherwise-equal groups.
        )
    )

    enabled_alert_rules = (  # QuerySet containing only enabled rules.
        alert_rules
        .filter(  # Additional filtering.
            is_enabled=True  # Boolean field condition.
        )
    )

    alert_rule_form = (  # Assignment: empty Django form used for creating a new rule.
        AlertRuleForm()  # Class instantiation concept: creates a form object.
    )

    # ========================================================
    # 15.6 GENERATED ALERT FORM OPTIONS
    # ========================================================

    alert_type_choices = (  # Assignment: retrieves model-configured alert-type options.
        _get_alert_type_choices()  # Helper-function call.
    )

    alert_severity_choices = (  # Assignment: retrieves model-configured severity options.
        _get_alert_severity_choices()  # Helper-function call.
    )

    # ========================================================
    # 15.7 SELECT DEFAULT MARKET BENCHMARK
    # ========================================================

    selected_symbol = (  # Assignment: stores validated Dashboard ticker.
        _get_selected_dashboard_symbol(  # Helper-function call.
            request  # Pass current HTTP request into helper.
        )
    )

    # ========================================================
    # 15.8 STORED POSTGRESQL HISTORICAL GRAPH DATA
    # ========================================================

    chart_rows = (  # Assignment: browser-friendly stored historical observations.
        _get_dashboard_chart_rows(  # Helper-function call.
            selected_symbol  # Argument: ticker chosen above.
        )
    )

    available_chart_symbols = (  # Assignment: benchmark tickers that currently have stored MarketData.
        _get_available_chart_symbols()  # Helper-function call with no arguments.
    )

    # ========================================================
    # 15.9 MARKET CONDITION
    # ========================================================

    market_condition = (  # Assignment: latest MarketRegime summary for selected ticker.
        _get_latest_market_condition(  # Helper call.
            selected_symbol  # Argument.
        )
    )

    # ========================================================
    # 15.10 DATA HEALTH
    # ========================================================

    data_health = (  # Assignment: stores global MarketData statistics.
        _get_market_data_health()  # Helper-function call.
    )

    # ========================================================
    # 15.11 DASHBOARD TEMPLATE CONTEXT
    # ========================================================

    context = {  # Dictionary: all values that dashboard.html can use.
        "active_strategy_count":
            active_strategies.count(),  # ORM count: number of active strategies.
        "strategy_count":
            strategies.count(),  # ORM count: number of all user strategies.
        "backtest_count":
            backtests.count(),  # ORM count: number of user's backtests.
        "avg_win_rate":
            average_win_rate_pct,  # Python numeric value already converted to percentage.
        "market_data_count":
            data_health[
                "total_rows"
            ],  # Dictionary indexing: retrieve total_rows from data_health.
        "strategies":
            strategies,  # QuerySet available to dashboard template.
        "latest_backtest":
            latest_backtest,  # One model object or None.
        "recent_backtests":
            backtests[:5],  # QuerySet slicing: only five newest backtests.
        "alerts":
            alerts,  # QuerySet of generated alerts.
        "active_alerts":
            active_alerts,  # QuerySet of active alerts.
        "active_alert_count":
            active_alerts.count(),  # ORM count.
        "unread_alert_count":
            unread_alerts.count(),  # ORM count.
        "alert_type_choices":
            alert_type_choices,  # Model metadata choices.
        "alert_severity_choices":
            alert_severity_choices,  # Model metadata choices.
        "alert_rules":
            alert_rules,  # QuerySet of configurable monitoring rules.
        "alert_rule_count":
            alert_rules.count(),  # ORM count.
        "enabled_alert_rules":
            enabled_alert_rules,  # QuerySet of enabled monitoring rules.
        "enabled_alert_rule_count":
            enabled_alert_rules.count(),  # ORM count.
        "alert_rule_form":
            alert_rule_form,  # Django form object.
        "dashboard_benchmarks":
            DASHBOARD_BENCHMARKS,  # Dictionary constant.
        "selected_symbol":
            selected_symbol,  # Current ticker string.
        "available_chart_symbols":
            available_chart_symbols,  # Python list.
        "market_chart_rows":
            chart_rows,  # Python list of dictionaries.
        "market_chart_has_data":
            bool(  # Type conversion: converts the list into True when it contains rows and False when empty.
                chart_rows
            ),
        "market_condition":
            market_condition,  # Dictionary or None.
        "data_health":
            data_health,  # Dictionary containing MarketData statistics.
        "dashboard_refresh_seconds":
            DASHBOARD_REFRESH_SECONDS,  # Integer configuration constant.
    }

    # ========================================================
    # 15.12 RENDER DASHBOARD
    # ========================================================

    return render(  # Django rendering shortcut.
        request,  # Current request.
        "dashboard.html",  # Template name.
        context,  # Context dictionary.
    )


