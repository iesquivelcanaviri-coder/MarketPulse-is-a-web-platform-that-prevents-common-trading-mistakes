# 19. DELETE ALERT RULE
# ============================================================

@login_required
@require_POST
def delete_alert_rule(
    request,
    rule_id,
):
    """
    Permanently delete a monitoring AlertRule.

    IMPORTANT:

    Deleting a rule does NOT delete existing generated Alert
    records.

    This preserves historical notification information while
    allowing the user to stop monitoring a condition.
    """


    # ========================================================
    # 19.1 FIND CURRENT USER'S RULE
    # ========================================================

    alert_rule = (
        get_object_or_404(
            AlertRule,
            pk=rule_id,
            user=request.user,
        )
    )


    # Save information before deleting the database object.

    symbol = (
        alert_rule.symbol
    )


    condition = (
        alert_rule.condition_display
    )


    # ========================================================
    # 19.2 DELETE RULE
    # ========================================================

    alert_rule.delete()


    # ========================================================
    # 19.3 USER FEEDBACK
    # ========================================================

    messages.success(
        request,
        (
            f"{symbol} alert rule "
            f"({condition}) was deleted."
        ),
    )


    # ========================================================
    # 19.4 RETURN TO DASHBOARD
    # ========================================================

    return redirect(
        "dashboard"
    )